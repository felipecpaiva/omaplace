#!/usr/bin/env bash
# Regenerates lua/tests/fixtures/geometry-golden.lua by running omagnet's geometry.lua on fixed inputs.
# Usage: bash tools/gen-geometry-golden.sh <path-to-omagnet-checkout>
# The committed output is what the tests use, so only the person refreshing the vectors needs omagnet.
set -euo pipefail
root=$(cd "$(dirname "$0")/.." && pwd)
src=${1:?usage: gen-geometry-golden.sh <omagnet checkout>}
commit=$(git -C "$src" log -1 --format=%h -- lua/geometry.lua)
out="$root/lua/tests/fixtures/geometry-golden.lua"

lua - "$src/lua/geometry.lua" "$commit" > "$out" <<'LUA'
local G = dofile(arg[1])
local function num(v) return string.format("%.17g", v) end
local function rect(r) return string.format("{ x = %d, y = %d, w = %d, h = %d }", r.x, r.y, r.w, r.h) end
local function frac(f) return string.format("{ %s, %s, %s, %s }", num(f[1]), num(f[2]), num(f[3]), num(f[4])) end

local mons = {}
for _, scale in ipairs({ 1, 1.25, 1.6, 2 }) do
  for _, transform in ipairs({ 0, 1 }) do
    for _, size in ipairs({ { 1920, 1080 }, { 2560, 1440 }, { 2880, 1800 }, { 1366, 768 } }) do
      mons[#mons + 1] = { x = 0, y = 0, width = size[1], height = size[2], scale = scale, transform = transform,
        reserved = { left = 0, top = 26, right = 0, bottom = 0 } }
    end
  end
end
mons[#mons + 1] = { x = 1920, y = 0, width = 2560, height = 1440, scale = 1.25, transform = 0,
  reserved = { left = 4, top = 30, right = 6, bottom = 10 } }
local reserves = { {}, { top = 0, bottom = 40 }, { left = 12, right = 12, top = 8 } }
local fracs = {
  { 0, 0, 1, 1 }, { 0, 0, 0.5, 1 }, { 0.5, 0, 0.5, 1 }, { 0, 0, 1 / 3, 1 }, { 1 / 3, 0, 1 / 3, 1 },
  { 2 / 3, 0, 1 / 3, 1 }, { 0.25, 0.25, 0.5, 0.5 }, { 0.1, 0.2, 0.7, 0.65 }, { 1 / 6, 0, 2 / 3, 1 },
}
local margins = { {}, { margin = 8 }, { margin = 7, edge_tight = false } }

io.write("-- Generated by tools/gen-geometry-golden.sh from omagnet commit ", arg[2], ". Do not edit by hand.\n")
io.write("return {\n  omagnet_commit = \"", arg[2], "\",\n  usable = {\n")
for _, m in ipairs(mons) do
  for _, rs in ipairs(reserves) do
    local a = G.usable(m, rs)
    local lw, lh = G.logical_size(m)
    io.write(string.format("    { mon = { x = %d, y = %d, width = %d, height = %d, scale = %s, transform = %d, reserved = { left = %d, top = %d, right = %d, bottom = %d } },\n",
      m.x, m.y, m.width, m.height, num(m.scale), m.transform, m.reserved.left, m.reserved.top, m.reserved.right, m.reserved.bottom))
    io.write(string.format("      reserve = { top = %d, bottom = %d, left = %d, right = %d }, area = %s, logical = { %d, %d } },\n",
      rs.top or 0, rs.bottom or 0, rs.left or 0, rs.right or 0, rect(a), lw, lh))
  end
end
io.write("  },\n  place_frac = {\n")
for _, m in ipairs(mons) do
  local a = G.usable(m)
  for _, f in ipairs(fracs) do
    for _, o in ipairs(margins) do
      io.write(string.format("    { area = %s, frac = %s, margin = %d, edge_tight = %s, rect = %s },\n",
        rect(a), frac(f), o.margin or 0, tostring(o.edge_tight ~= false), rect(G.place_frac(a, f, o))))
    end
  end
end
io.write("  },\n  transfer = {\n")
local rects = { { x = 100, y = 80, w = 640, h = 480 }, { x = 0, y = 26, w = 960, h = 1054 }, { x = 1800, y = 900, w = 300, h = 300 } }
for i, ma in ipairs(mons) do
  local mb = mons[(i * 7) % #mons + 1]
  local from, to = G.usable(ma), G.usable(mb)
  for _, r in ipairs(rects) do
    io.write(string.format("    { rect = %s, from = %s, to = %s, out = %s },\n", rect(r), rect(from), rect(to), rect(G.transfer(r, from, to))))
  end
end
io.write("  },\n}\n")
LUA
echo "wrote $out (omagnet $commit)"
